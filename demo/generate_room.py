#!/usr/bin/env python3
"""Generate ray-cast TXT scans and rigidly displaced initial submap frames."""
import argparse
from pathlib import Path
import sys

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src/occupancy_joining/scripts'))
from geometry import se2, pose2


def rectangle(x0, x1, y0, y1):
    corners = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    return [(corners[i], corners[(i + 1) % 4]) for i in range(4)]


def generate(output):
    output.mkdir(parents=True, exist_ok=False)
    walls = rectangle(-6, 8, -5, 6)
    walls += [((3, -3), (3, .6)), ((-3, 2.5), (-.2, 2.5))]
    walls += rectangle(-3.9, -2.8, -2.8, -1.8) + rectangle(4, 5.5, 2, 3.5)
    segments = np.asarray(walls, dtype=float)
    phase = np.arange(90) * 2 * np.pi / 30
    truth = np.column_stack((1.3 * np.cos(phase), np.sin(phase), .2 * np.sin(phase)))
    angles = np.linspace(-np.pi, np.pi, 720, endpoint=False)
    biases = np.array([[0, 0, 0], [.65, -.45, .06], [-.55, .5, -.05]])
    ranges, initial = [], []
    for i, pose in enumerate(truth):
        direction = np.column_stack((np.cos(angles + pose[2]), np.sin(angles + pose[2])))
        nearest = np.full(len(angles), np.inf)
        for start, end in segments:
            edge = end - start
            delta = start - pose[:2]
            denominator = direction[:, 0] * edge[1] - direction[:, 1] * edge[0]
            with np.errstate(divide='ignore', invalid='ignore'):
                distance = (delta[0] * edge[1] - delta[1] * edge[0]) / denominator
                fraction = (delta[0] * direction[:, 1] - delta[1] * direction[:, 0]) / denominator
            good = (np.abs(denominator) > 1e-12) & (distance > 0) & (fraction >= 0) & (fraction <= 1)
            nearest = np.minimum(nearest, np.where(good, distance, np.inf))
        if not np.isfinite(nearest).all():
            raise ValueError('The enclosing room must intersect every beam')
        ranges.append(nearest)
        initial.append(pose2(se2(biases[i // 30]) @ se2(pose)))
    for name, data in [('Range.txt', ranges), ('Pose.txt', initial), ('GT.txt', truth)]:
        np.savetxt(output / name, data, fmt='%.17g')
    config = dict(
        input=dict(type='txt', dataset='.', ground_truth='GT.txt', angle_min=float(angles[0]), angle_max=float(angles[-1])),
        submaps=dict(scans_per_submap=30, local_resolution=.1, cell_update_policy='hit_priority'),
        optimizer=dict(model='globalized_inverse', global_resolution=.1, max_iterations=70, continuation_sigmas=[8, 4, 2, 1, 0]),
        display=dict(resolution=.05, cell_update_policy='hit_priority'))
    (output / 'demo.yaml').write_text(yaml.safe_dump(config, sort_keys=False))
    (output / 'DATA_NOTICE.txt').write_text('Independent synthetic ray-cast dataset generated by demo/generate_room.py.\nDistributed under the repository MIT license.\n90 scans; 720 beams; three overlapping, internally exact local submaps.\nInitial world-frame biases: [0,0,0], [0.65,-0.45,0.06], [-0.55,0.5,-0.05] in metres/radians.\nGT.txt is evaluation-only; the first submap fixes the common gauge.\n')
    print(output.resolve())


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    generate(parser.parse_args().output)
